"""Pure generators for the launchers an installation runs.

Two launchers exist, and both are text contracts rather than process logic:

- the **package wrapper** ``<code>/bin/frontier.cmd`` shipped inside a
  distribution package.  It sets the working directory to the package root and
  runs the bundled interpreter (``%~dp0..\\runtime\\python.exe``) through
  ``-m hostrun.cli``.  It never consults ``PATH`` and never names a bare
  ``python``/``py``, so an installation runs with no system Python.  The file is
  written with CRLF bytes; the first line is ``@echo off``.
- the **console launcher** ``<code>/bin/frontier-console.cmd`` generated by
  ``console install`` (and by ``install migrate``).  In a source installation it
  pins the recorded absolute interpreter; in a package installation it delegates
  to the wrapper instead.  ``%*`` forwards arguments verbatim, so
  ``frontier-console control start`` reaches the CLI while a double-click still
  starts the resident console with no arguments.

Keeping both generators in one module is deliberate: ``hostrun.console`` and
``hostrun.migration`` used to duplicate the console text, and the package build
now needs the same wrapper bytes.  A byte difference would break the pinned
launcher tests or the "no PATH" guarantee.
"""

from __future__ import annotations

import json
from pathlib import Path

CONSOLE_TITLE = "frontier-console"
#: Package-relative paths the wrapper and the console launcher live at.
WRAPPER_REL = Path("bin") / "frontier.cmd"
RUNTIME_PYTHON_REL = Path("runtime") / "python.exe"
LOCK_REL = Path(".frontier") / "dist.lock.json"

_WRAPPER_LINES = (
    "@echo off",
    'cd /d "%~dp0.."',
    '"%~dp0..\\runtime\\python.exe" -m hostrun.cli %*',
)


def wrapper_text() -> str:
    """The package wrapper's exact text, CRLF lines and a trailing CRLF.

    The runtime path is relative to the wrapper (``%~dp0`` is the directory of
    the executing batch file), so the package keeps working when the user renames
    or moves the whole code directory.
    """
    return "\r\n".join(_WRAPPER_LINES) + "\r\n"


def write_wrapper(path: str | Path) -> Path:
    """Write :func:`wrapper_text` as CRLF bytes, creating parent directories."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8", newline="") as handle:
        handle.write(wrapper_text())
    return target


def package_mode(code: str | Path) -> bool:
    """Whether ``code`` is an installed package that carries the wrapper.

    Both facts matter: the install lock proves the directory came from a
    distribution package, and the wrapper file is what the console launcher can
    delegate to.  A source installation has neither, so it keeps the absolute
    interpreter form.
    """
    code_path = Path(code)
    try:
        lock = json.loads((code_path / LOCK_REL).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    if not isinstance(lock, dict) or lock.get("distribution") != "package":
        return False
    return (code_path / WRAPPER_REL).is_file()


def console_script_text(
    code: str | Path,
    archive: str | Path,
    python: str,
    *,
    package: bool = False,
) -> str:
    """The fixed double-click launcher argv (title first, ``%*`` last).

    ``package`` selects the package-install form: delegate to ``frontier.cmd``,
    which owns the bundled interpreter, instead of naming an interpreter here.
    """
    if package:
        return (
            f"title {CONSOLE_TITLE}\n"
            f'call "%~dp0frontier.cmd" --code "{Path(code)}" '
            f'--archive "{Path(archive)}" console %*\n'
        )
    return (
        f"title {CONSOLE_TITLE}\n"
        f'cd /d "{Path(code)}"\n'
        f'"{python}" -m hostrun.cli --code "{Path(code)}" '
        f'--archive "{Path(archive)}" console %*\n'
    )
